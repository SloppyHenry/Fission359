"""Draws the placeholder app icon and the macOS disk-image background.

Writes into packaging/icons/: the SVG, PNGs in all sizes and dmg-background(@2x).png.
Needs Pillow (pip install pillow). The results are committed, so building packages does not
need this script. Replace it (or the files) when a real icon exists.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw

APP_ID = "io.github.sloppyhenry.Fission359"
SIZES = (16, 32, 48, 64, 128, 256, 512, 1024)

# Design colours (docs/08-gestaltung.md): panel, accent, accent-text, accent-line.
BACKGROUND = "#1F2023"
FACE_TOP = "#7FB0FF"
FACE_LEFT = "#2563D9"
FACE_RIGHT = "#1B4DB0"
EDGE = "#5B97FF"

# Geometry in a 1024 x 1024 box: rounded square (80 %, macOS icon grid) and an isometric cube.
SQUARE = (100, 100, 924, 924)
RADIUS = 185
CUBE_CENTER = (512, 530)
CUBE_R = 270  # distance centre -> outer corner


def cube_points():
    cx, cy = CUBE_CENTER
    r = CUBE_R
    h = r / 2
    w = r * 0.866
    top = [(cx, cy - r), (cx + w, cy - h), (cx, cy), (cx - w, cy - h)]
    left = [(cx - w, cy - h), (cx, cy), (cx, cy + r), (cx - w, cy + h)]
    right = [(cx + w, cy - h), (cx + w, cy + h), (cx, cy + r), (cx, cy)]
    return top, left, right


def svg() -> str:
    top, left, right = cube_points()

    def poly(points, colour):
        pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in points)
        return (f'  <polygon points="{pts}" fill="{colour}" stroke="{EDGE}" '
                f'stroke-width="6" stroke-linejoin="round"/>')

    x0, y0, x1, y1 = SQUARE
    return "\n".join([
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- SPDX-FileCopyrightText: Fission359 contributors -->',
        f'<!-- SPDX-License-Identifier: GPL-3.0-or-later -->',
        '<!-- Placeholder icon, generated by scripts/tools/make_icons.py -->',
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">',
        f'  <rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" rx="{RADIUS}" '
        f'fill="{BACKGROUND}"/>',
        poly(top, FACE_TOP), poly(left, FACE_LEFT), poly(right, FACE_RIGHT),
        '</svg>', ''])


def render(size: int) -> Image.Image:
    scale = 4
    canvas = 1024 * scale
    image = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle([c * scale for c in SQUARE], radius=RADIUS * scale, fill=BACKGROUND)
    for points, colour in zip(cube_points(), (FACE_TOP, FACE_LEFT, FACE_RIGHT)):
        scaled = [(x * scale, y * scale) for x, y in points]
        draw.polygon(scaled, fill=colour)
        draw.line(scaled + [scaled[0]], fill=EDGE, width=6 * scale, joint="curve")
    return image.resize((size, size), Image.LANCZOS)


def dmg_background(scale: int) -> Image.Image:
    """660 x 400 pt window: app icon at the left, Applications link at the right, arrow between."""
    width, height = 660 * scale, 400 * scale
    image = Image.new("RGBA", (width, height), "#131416")
    draw = ImageDraw.Draw(image)
    y = 200 * scale
    x0, x1 = 270 * scale, 390 * scale
    draw.line([(x0, y), (x1 - 14 * scale, y)], fill="#5B97FF", width=6 * scale)
    draw.polygon([(x1, y), (x1 - 26 * scale, y - 16 * scale), (x1 - 26 * scale, y + 16 * scale)],
                 fill="#5B97FF")
    return image


def main() -> int:
    out = Path(__file__).resolve().parents[2] / "packaging" / "icons"
    (out / "png").mkdir(parents=True, exist_ok=True)
    (out / f"{APP_ID}.svg").write_text(svg(), encoding="utf-8")
    for size in SIZES:
        render(size).save(out / "png" / f"icon-{size}.png")
    dmg_background(1).convert("RGB").save(out / "dmg-background.png")
    dmg_background(2).convert("RGB").save(out / "dmg-background@2x.png")
    print(f"Wrote icons to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
